export const JobExamples = {
    CancelledJobExample,
    FailedJobExample,
    QueuedJobExample,
    RunningJobExample,
    FinishedQuantumJobExample
}

export const test = base.extend({
    page: async ({ page }, use) => {

        // 1. Intercept Haskell Language Server WebSocket
        await page.routeWebSocket('ws://localhost:3000/api/*', ws => {
            ws.onMessage(message => {
                const parsed = JSON.parse(message as string);
                if (parsed.method === 'initialize') {
                    ws.send(JSON.stringify({
                        jsonrpc: '2.0',
                        id: parsed.id,
                        result: { capabilities: { hoverProvider: true } }
                    }));
                }
            });
        });

        // 2. Intercept Global HTTP Routes for /run-protocol
        await page.route('**/api/run-protocol', async route => {
            if (route.request().method() === 'POST') {
                // By default, instantly queue the job
                await route.fulfill({ status: 202, json: JobExamples.RunningJobExample });
            } else {
                await route.fallback();
            }
        });

        await page.route('**/api/run-protocol/*', async route => {
            const method = route.request().method();

            if (method === 'GET') {
                await route.fulfill({ status: 200, json: JobExamples.FinishedQuantumJobExample });
            } else if (method === 'DELETE') {
                await route.fulfill({ status: 200, json: JobExamples.CancelledJobExample });
            } else if (method === 'POST') {
                await route.fulfill({ status: 202, json: JobExamples.QueuedJobExample });
            } else {
                await route.fallback();
            }
        });

        // 3. Pass the fully mocked page to your tests
        await use(page);
    },
});

